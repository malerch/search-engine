-- Convert pairs of filenames and words to a table
makeTable :: Pairs -> Table
makeTable pairs = aux sortedPairs
    where
        -- Base cases: empty list (empty table), one pair (table with one entry)
        aux [] = []
        aux [(word, filename)] = (word, nub (map snd (filter ((==word) . fst)
            sortedPairs))) : []
        aux ((word, _) : (word2, filename2) : pairs)
            -- Check for runs of duplicate words
            | word /= word2 =
                -- Construct filename list by filtering by equal keys, taking
                -- the filename and removing duplicates
                (word, nub (map snd (filter ((==word) . fst) sortedPairs)))
                : aux ((word2, filename2) : pairs)
            | otherwise = aux ((word2, filename2) : pairs)
        -- Sort pairs so duplicates form runs, efficient to identify
        sortedPairs = sort pairs




{-
    You must also implement:

    a function isValidTable, which checks if a table is valid as described above
    (no dup keys, no dup filenames, no empty lists) a quickCheck property to
    check that tables generated by your makeTable are valid
-}

isValidTable :: Table -> Bool
isValidTable [] = True
isValidTable tab@((word, filenames) : xs) =
    -- Checks for dup keys, dup filenames and empty lists
    (tab == dedupKeys tab && noDupFilenames tab && noEmptyLists tab)
    -- Helper functions
    where
        -- Remove dup keys
        dedupKeys = nubBy (\(k1, _) (k2, _) -> k1 == k2)
        -- Check for dup filenames
        noDupFilenames [] = True
        noDupFilenames ((_, filenames) : xs) =
            filenames == nub filenames && noDupFilenames xs
        -- Check for empty lists
        noEmptyLists [] = True
        noEmptyLists ((_, filenames) : xs) = all ((/= []) . snd) tab



