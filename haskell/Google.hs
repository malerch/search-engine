type Pairs = [(String,FilePath)]     -- Input: Pairs of words and filenames

type Table = [(String, [FilePath])]  -- Association list of words to filenames
{-
    There must be no duplicate keys.
    The keys must be sorted in ascending order.
    There must be no duplicate filenames associated with the same key.
    There must be no empty lists associated with a key.
-}

-- We provide the lookup function for you
